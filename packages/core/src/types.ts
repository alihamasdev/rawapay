import type { RawaPayError } from "./errors";
import type { HttpClient } from "./http";

/**
 * Result pattern types for predictable error handling.
 */
export type SuccessResult<T> = {
	data: T;
	error: null;
};

export type ErrorResult<E = RawaPayError> = {
	data: null;
	error: E;
};

export type Result<T, E = RawaPayError> = SuccessResult<T> | ErrorResult<E>;

/**
 * Normalized payment statuses across all providers.
 */
export type PaymentStatus = "succeeded" | "pending" | "processing" | "failed" | "cancelled" | "expired";

/**
 * Standardized payment entity returned to developers.
 */
export interface Payment {
	/** Unique transaction identifier generated by RawaPay */
	id: string;
	/** Provider used for this payment, e.g. "jazzcash", "easypaisa" */
	provider: string;
	/** Standardized lifecycle status of the transaction */
	status: PaymentStatus;
	/** Payment amount in Pakistani Rupees (PKR) */
	amount: number;
	/** Raw amount formatted for the gateway */
	rawAmount?: string;
	/** Currency code, always PKR */
	currency: "PKR";
	/** Human-readable memo or developer's order reference */
	description?: string;
	/** Gateway raw response code (e.g. "000") */
	responseCode: string;
	/** Gateway raw response message */
	responseMessage: string;
	/** Bank / Gateway Retrieval Reference Number (RRN) for reconciliation */
	retrievalRefNo?: string;
	/** Full unmodified raw response payload from the gateway */
	raw: Record<string, unknown>;
	/** ISO 8601 creation timestamp */
	createdAt: string;
}

/**
 * Unified error codes categorized across all payment providers.
 */
export type RawaPayErrorCode =
	| "INVALID_REQUEST"
	| "INVALID_PARAMETER"
	| "INVALID_CREDENTIALS"
	| "INVALID_SIGNATURE"
	| "CARD_BLOCKED"
	| "ACCOUNT_INACTIVE"
	| "ACCOUNT_NOT_FOUND"
	| "DUPLICATE_REFERENCE"
	| "INVALID_TIMESTAMP"
	| "INSUFFICIENT_FUNDS"
	| "AUTHENTICATION_FAILED"
	| "TRANSACTION_EXPIRED"
	| "TRANSACTION_CANCELLED"
	| "PAYMENT_PENDING"
	| "LIMIT_EXCEEDED"
	| "PAYMENT_FAILED"
	| "PAYMENT_REJECTED"
	| "GATEWAY_ERROR"
	| "UNKNOWN_ERROR";

/**
 * Common payment parameters required across all drivers.
 */
export interface BasePaymentParams {
	/** Payment amount in PKR */
	amount: number;
	/** Short memo, note, or developer's merchant order reference (e.g. "ORDER-9042") */
	description?: string;
}

/**
 * Parameters for checking transaction status.
 */
export interface GetStatusParams {
	/** Unified payment ID returned by payment.create */
	paymentId: string;
	[key: string]: unknown;
}

/**
 * Execution environment for payment providers and RawaPay.
 */
export type PaymentEnvironment = "sandbox" | "production";

/**
 * Supported or custom payment provider identifiers.
 * Autocompletes built-in providers while accepting custom provider names.
 */
export type Provider = "jazzcash" | "easypaisa" | (string & {});

/**
 * Helper to infer the string literal name from a PaymentDriver or provider factory function.
 */
export type InferProviderName<T> = T extends { readonly name: infer N extends string }
	? N
	: T extends (...args: any[]) => { readonly name: infer N extends string }
		? N
		: string;

/**
 * Extracts a union of literal provider names from configured providers.
 * If no providers are configured or if given an unconstrained array, defaults to `Provider`.
 */
export type ExtractProviderNames<TProviders extends readonly unknown[] | undefined> = TProviders extends readonly [unknown, ...unknown[]]
	? InferProviderName<TProviders[number]>
	: TProviders extends readonly (infer U)[]
		? [U] extends [never]
			? Provider
			: string extends InferProviderName<U>
				? Provider
				: InferProviderName<U>
		: Provider;

/**
 * Gateway base URLs mapped by payment environment.
 */
export type DriverBaseUrls = Record<PaymentEnvironment, string>;

/**
 * Contract that every payment provider driver must implement.
 */
export interface PaymentDriver<TPaymentParams = unknown, TStatusParams = GetStatusParams, TName extends string = string> {
	/** Unique identifier for the provider driver (e.g. "jazzcash") */
	readonly name: TName;

	/** Gateway base URLs for sandbox and production environments */
	readonly baseUrls: DriverBaseUrls;

	/** HTTP client instance managed and configured by the core client */
	http: HttpClient;

	/** Direct payment initiation */
	createPayment(params: TPaymentParams): Promise<Result<Payment, RawaPayError>>;

	/** Checks status for a previously initiated transaction */
	getStatus(params: TStatusParams): Promise<Result<Payment, RawaPayError>>;

	/** Verifies the cryptographic signature / integrity of an incoming IPN callback */
	verifyCallback?(body: Record<string, unknown>): boolean;
}

/**
 * A provider can be an initialized PaymentDriver or a factory function.
 */
export type PaymentProviderFactory<TDriver extends PaymentDriver = PaymentDriver> = () => TDriver;

export type PaymentProvider = PaymentDriver<any, any> | PaymentProviderFactory<any>;

/**
 * Generic options for payment creation in core.
 */
export interface CreatePaymentOptions<TProvider extends string = Provider> extends BasePaymentParams {
	/** Identifier of the target provider (e.g. "jazzcash", "easypaisa") */
	provider: TProvider;
	/** Customer mobile phone number (03xxxxxxxxx) */
	phone?: string;
	/** Last 6 digits or full 13-digit CNIC (for mobile wallets) */
	cnic?: string;
	[key: string]: unknown;
}

/**
 * Options for checking transaction status in core.
 */
export interface PaymentStatusOptions<TProvider extends string = Provider> {
	/** Identifier of the target provider (e.g. "jazzcash", "easypaisa") */
	provider: TProvider;
	/** Unified payment ID returned from payment.create */
	paymentId: string;
	[key: string]: unknown;
}

/**
 * RawaPay initialization options.
 */
export interface RawaPayOptions<TProviders extends readonly PaymentProvider[] = readonly PaymentProvider[]> {
	/** Target environment mode: "sandbox" or "production" (defaults to "sandbox") */
	environment?: PaymentEnvironment;
	/** HTTP request timeout in milliseconds (defaults to 30000) */
	timeoutMs?: number;
	/** Configured payment providers passed as an array */
	providers?: TProviders;
	/** Custom fetch implementation for proxies, enterprise mTLS, or test runners */
	fetch?: typeof fetch;
	/** Pre-configured HttpClient instance to share across all providers */
	httpClient?: HttpClient;
}
